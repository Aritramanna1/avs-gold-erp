export const getPlatformEmailConfig = loadPlatformSenderConfig;

export async function sendPlatformEmail(params: {
  tenantId?: string;
  templateKey?: string;
  recipientEmail: string;
  recipientName?: string;
  variables?: Record<string, string | number>;
  subject?: string;
  htmlBody?: string;
}): Promise<{ ok: boolean; error?: string }> {
  const templates = await loadEmailTemplates();
  const tmpl = templates.find((t) => t.templateCode === params.templateKey) || templates[0];
  const rendered = tmpl && params.variables
    ? renderEmailBody(tmpl.bodyHtml, params.variables)
    : params.htmlBody || "";
  const subj = tmpl && params.variables
    ? Object.entries(params.variables).reduce((acc, [k, v]) => acc.replace(new RegExp(k.replace(/[{}]/g, "\\$&"), "g"), String(v)), tmpl.subject)
    : params.subject || tmpl?.subject || "Notification from AVS Gold ERP";

  return dispatchPlatformEmail({
    to: params.recipientEmail,
    subject: subj,
    htmlBody: rendered,
    tenantId: params.tenantId,
    messageType: params.templateKey || "notification",
  });
}




