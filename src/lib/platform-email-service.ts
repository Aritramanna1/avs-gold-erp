/**
 * Load platform sender configuration from platform_settings table.
 */
export async function loadPlatformSenderConfig(): Promise<PlatformEmailSenderConfig> {
  // First check localStorage cache
  let localConfig: Partial<PlatformEmailSenderConfig> | null = null;
  try {
    const raw = localStorage.getItem("platform_email_sender_config");
    if (raw) localConfig = JSON.parse(raw);
  } catch {}

  try {
    const { data } = await supabase
      .from("platform_settings")
      .select("key, value")
      .in("key", [
        "email.from_email",
        "email.from_name",
        "email.reply_to",
        "email.smtp_host",
        "email.smtp_port",
        "email.support_phone",
        "email.support_email",
        "email.portal_url",
        "email.legal_disclaimer",
      ]);

    if (!data || data.length === 0) {
      return localConfig ? { ...DEFAULT_SENDER_CONFIG, ...localConfig } : DEFAULT_SENDER_CONFIG;
    }

    const map = new Map(data.map((r: { key: string; value: any }) => [r.key, r.value]));
    return {
      fromEmail: String(map.get("email.from_email") || localConfig?.fromEmail || DEFAULT_SENDER_CONFIG.fromEmail),
      fromName: String(map.get("email.from_name") || localConfig?.fromName || DEFAULT_SENDER_CONFIG.fromName),
      replyTo: String(map.get("email.reply_to") || localConfig?.replyTo || DEFAULT_SENDER_CONFIG.replyTo),
      smtpHost: String(map.get("email.smtp_host") || localConfig?.smtpHost || DEFAULT_SENDER_CONFIG.smtpHost),
      smtpPort: Number(map.get("email.smtp_port") || localConfig?.smtpPort || DEFAULT_SENDER_CONFIG.smtpPort),
      supportPhone: String(map.get("email.support_phone") || localConfig?.supportPhone || DEFAULT_SENDER_CONFIG.supportPhone),
      supportEmail: String(map.get("email.support_email") || localConfig?.supportEmail || DEFAULT_SENDER_CONFIG.supportEmail),
      portalUrl: String(map.get("email.portal_url") || localConfig?.portalUrl || DEFAULT_SENDER_CONFIG.portalUrl),
      legalDisclaimer: String(map.get("email.legal_disclaimer") || localConfig?.legalDisclaimer || DEFAULT_SENDER_CONFIG.legalDisclaimer),
    };
  } catch {
    return localConfig ? { ...DEFAULT_SENDER_CONFIG, ...localConfig } : DEFAULT_SENDER_CONFIG;
  }
}

