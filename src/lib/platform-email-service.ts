/**
 * Load all central email templates
 */
export async function loadEmailTemplates(): Promise<EmailTemplateConfig[]> {
  try {
    const localRaw = localStorage.getItem("platform_email_templates");
    if (localRaw) {
      const parsed = JSON.parse(localRaw);
      if (typeof parsed === "object") {
        return Object.values(parsed) as unknown as EmailTemplateConfig[];
      }
    }
  } catch {}

  try {
    const { data } = await supabase
      .from("platform_settings")
      .select("value")
      .eq("key", "email.templates")
      .maybeSingle();

    if (data?.value && typeof data.value === "object") {
      return Object.values(data.value) as unknown as EmailTemplateConfig[];
    }
  } catch {
    // fallback
  }
  return Object.values(DEFAULT_EMAIL_TEMPLATES);
}

/**
 * Save email template
 */
export async function saveEmailTemplate(template: EmailTemplateConfig): Promise<void> {
  const all = await loadEmailTemplates();
  const map: Record<string, EmailTemplateConfig> = {};
  for (const t of all) map[t.templateCode] = t;
  map[template.templateCode] = { ...template, updatedAt: new Date().toISOString() };

  try {
    localStorage.setItem("platform_email_templates", JSON.stringify(map));
  } catch {}

  try {
    await supabase.from("platform_settings").upsert({
      key: "email.templates",
      value: map as any,
    });
  } catch {
    // Non-blocking if RLS restricts table writes; local cache is active
  }
}

/**
 * Render template with variables and inject mandatory AVS branded footer
 */
export function renderEmailBody(
  templateHtml: string,
  tokens: Record<string, string | number>,
  senderConfig?: Partial<PlatformEmailSenderConfig>,
): string {
  let rendered = templateHtml;
  for (const [key, val] of Object.entries(tokens)) {
    const pattern = new RegExp(key.replace(/[{}]/g, "\\$&"), "g");
    rendered = rendered.replace(pattern, String(val ?? ""));
  }
  const footer = generateAvsBrandedFooter(senderConfig);
  return `
    <div style="background-color: #ffffff; padding: 24px; max-width: 640px; margin: 0 auto; border-radius: 8px; border: 1px solid #e2e8f0;">
      ${rendered}
      ${footer}
    </div>
  `;
}

/**
 * Dispatch transactional email from the platform sender with automatic branding and audit logging
 */
export async function dispatchPlatformEmail(input: {
  to: string;
  subject: string;
  htmlBody: string;
  tenantId?: string;
  tenantName?: string;
  messageType?: string;
  documentRef?: string;
  attachments?: Array<{ filename: string; contentBase64: string; contentType?: string }>;
}): Promise<{ ok: boolean; error?: string }> {
  const senderCfg = await loadPlatformSenderConfig();
  
  // Ensure AVS Branded footer is attached if not already present
  const finalHtml = input.htmlBody.includes("AVS GOLD ERP")
    ? input.htmlBody
    : `${input.htmlBody}${generateAvsBrandedFooter(senderCfg)}`;

  try {
    const res = await fetch("/api/email/send.php", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        to: input.to,
        subject: input.subject,
        htmlBody: finalHtml,
        attachments: input.attachments || [],
        fromEmail: senderCfg.fromEmail,
        fromName: senderCfg.fromName,
        replyTo: senderCfg.replyTo,
      }),
    });

    const data = await res.json().catch(() => ({ success: res.ok }));
    const isSuccess = Boolean(res.ok && data?.success !== false);

    // Record in platform delivery audit log
    await supabase.from("platform_audit_events").insert({
      action: isSuccess ? "EMAIL_DISPATCHED" : "EMAIL_FAILED",
      target_type: "email",
      reason: `${input.messageType || "General"}: ${input.subject} -> ${input.to} (${isSuccess ? "Sent" : data?.error || "Failed"})`,
    });

    return { ok: isSuccess, error: isSuccess ? undefined : data?.error || `HTTP ${res.status}` };
  } catch (err: any) {
    await supabase.from("platform_audit_events").insert({
      action: "EMAIL_FAILED",
      target_type: "email",
      reason: `Exception sending to ${input.to}: ${err.message}`,
    });
    return { ok: false, error: err.message };
  }
}

